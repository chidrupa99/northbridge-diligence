def _load_ticker_map() -> list[dict]:
    cached = _cache.get("__tickers__")
    if cached is not None:
        return cached
    data = _get_json("https://www.sec.gov/files/company_tickers.json")
    rows = [
        {
            "cik": int(row["cik_str"]),
            "cik10": str(row["cik_str"]).zfill(10),
            "ticker": row["ticker"].upper(),
            "title": row["title"],
        }
        for row in data.values()
    ]
    _cache.put("__tickers__", rows)
    return rows


def _pub(row: dict) -> dict:
    return {
        "cik": row["cik"],
        "cik10": row["cik10"],
        "ticker": row["ticker"],
        "name": row["title"],
    }


def resolve_company(query: str, max_candidates: int = 5) -> dict:
    """
    Map a ticker or company name to a CIK.

    Returns {"resolved": {...}} on a confident match, or
            {"ambiguous": True, "candidates": [...]} when a name is ambiguous,
            so the caller/model can disambiguate rather than silently pick the
            wrong company.
    """
    if not query or not query.strip():
        raise InvalidArgument("Empty company query.")
    q = query.strip()
    rows = _load_ticker_map()

    # 1) Exact ticker match wins.
    exact = [r for r in rows if r["ticker"] == q.upper()]
    if exact:
        return {"resolved": _pub(exact[0])}

    # 2) Exact (case-insensitive) name match.
    ql = q.lower()
    name_exact = [r for r in rows if r["title"].lower() == ql]
    if len(name_exact) == 1:
        return {"resolved": _pub(name_exact[0])}

    # 3) Substring name match -> may be ambiguous.
    partial = [r for r in rows if ql in r["title"].lower()]
    if len(partial) == 1:
        return {"resolved": _pub(partial[0])}
    if len(partial) > 1:
        return {
            "ambiguous": True,
            "candidates": [_pub(r) for r in partial[:max_candidates]],
            "note": f"{len(partial)} companies matched '{query}'. "
                    "Pass a ticker or exact name to disambiguate.",
        }
    raise CompanyNotFound(
        f"No SEC-registered company matched '{query}'. "
        "Note: EDGAR only covers SEC filers (public/registered companies)."
    )


class AmbiguousCompany(EdgarError):
    """Raised when a data tool is handed a name that matches several filers.

    Carries the candidate list so the server layer can hand the model the same
    disambiguation payload `resolve_company` returns — the two paths agree.

    Not retryable: the same query returns the same ambiguity every time. It is
    resolved by the user picking a candidate, not by calling again.
    """

    code = "AMBIGUOUS_COMPANY"
    category = "client_error"

    def __init__(self, payload: dict):
        self.payload = payload
        super().__init__(payload.get("note", "Ambiguous company name."))

    def envelope(self) -> dict:
        # Candidates first, so the model reads the choice it has to offer the
        # user before the error framing around it.
        return {**self.payload, **super().envelope()}


def _resolve_cik(query: str) -> dict:
    """Internal: resolve to a single company or raise (used by data tools)."""
    res = resolve_company(query)
    if "resolved" in res:
        return res["resolved"]
    raise AmbiguousCompany(res)


