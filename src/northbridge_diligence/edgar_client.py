_TAG_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,119}$")
_ANNUAL_FORMS = ("10-K", "10-K/A")


def get_company_facts(cik10: str) -> dict:
    """Raw companyfacts blob for a filer — one HTTP call, then cached."""
    return _get_json(f"https://data.sec.gov/api/xbrl/companyfacts/CIK{cik10}.json")


def _fiscal_year_index(facts: dict) -> dict[str, int]:
    """
    Learn the filer's OWN fiscal-year labels from its filings.

    A 10-K's XBRL facts all carry the *report's* fy/fp (so FY2024's 10-K tags its
    FY2023 comparative as fy=2024 too). Within one accession, the fact with the
    latest period end IS the report's own year — so that period end maps to that
    fy label. Doing this across every accession gives us period_end -> fiscal
    year, which then labels the comparative facts correctly too.

    This matters because the naive `end.year` convention is wrong for retailers
    with January/February year ends.
    """
    by_accn: dict[str, tuple[str, int]] = {}
    for tag_data in facts.get("facts", {}).get("us-gaap", {}).values():
        for unit_facts in tag_data.get("units", {}).values():
            for f in unit_facts:
                if f.get("form") not in _ANNUAL_FORMS or f.get("fp") != "FY":
                    continue
                accn, end, fy = f.get("accn"), f.get("end"), f.get("fy")
                if not accn or not end or fy is None:
                    continue
                prev = by_accn.get(accn)
                if prev is None or end > prev[0]:
                    by_accn[accn] = (end, fy)
    return {end: fy for end, fy in by_accn.values()}


def _fy_label(end: str, fy_index: dict[str, int]) -> int:
    """
    Label a period end with the filer's own fiscal-year convention.

    Direct hit when the period was some 10-K's current year. Otherwise — true of
    the oldest comparatives, which only ever appear as prior-year columns — carry
    over the offset from the nearest period we *did* learn. Target's fiscal 2009
    ended 2010-01-30, so its offset is -1; without this, `end.year` would label
    both 2009-01-31 and 2010-01-30 as "2009" and one of the two years would be
    silently dropped.
    """
    if end in fy_index:
        return fy_index[end]
    if not fy_index:
        return int(end[:4])
    from datetime import date

    def _d(s: str) -> date:
        return date.fromisoformat(s)

    try:
        target = _d(end)
        nearest_end, nearest_fy = min(
            fy_index.items(), key=lambda kv: abs((_d(kv[0]) - target).days))
    except (TypeError, ValueError):
        return int(end[:4])
    return int(end[:4]) + (nearest_fy - int(nearest_end[:4]))


def _is_annual_duration(f: dict) -> bool:
    """Keep full-year duration facts; drop quarterly slices tagged inside a 10-K."""
    start, end = f.get("start"), f.get("end")
    if not start:
        return True  # instant fact (balance sheet) — no duration to check
    try:
        from datetime import date
        s = date.fromisoformat(start)
        e = date.fromisoformat(end)
    except (TypeError, ValueError):
        return True
    return 340 <= (e - s).days <= 400


def _preferred_unit(units: dict[str, list]) -> Optional[str]:
    """Prefer USD; otherwise the unit with the most observations. We never mix."""
    if not units:
        return None
    if "USD" in units:
        return "USD"
    return max(units, key=lambda u: len(units[u]))


def annual_series(facts: dict, cik: int, tag: str,
                  fy_index: Optional[dict[str, int]] = None) -> list[SourcedValue]:
    """
    The clean annual series for one XBRL tag, straight out of the companyfacts
    blob. Includes prior-year comparatives carried inside later 10-Ks, which is
    how we get 5+ years of history without 5 separate filings.
    """
    tag_data = facts.get("facts", {}).get("us-gaap", {}).get(tag)
    if not tag_data:
        return []
    units = tag_data.get("units", {})
    unit = _preferred_unit(units)
    if unit is None:
        return []
    if fy_index is None:
        fy_index = _fiscal_year_index(facts)

    # period_end -> every filing that reported it, so we can detect restatements.
    per_period: dict[str, list[dict]] = {}
    for f in units[unit]:
        if f.get("form") not in _ANNUAL_FORMS or f.get("fp") != "FY":
            continue
        if not f.get("end") or f.get("val") is None:
            continue
        if not _is_annual_duration(f):
            continue
        per_period.setdefault(f["end"], []).append(f)

    by_year: dict[int, SourcedValue] = {}
    for end, observations in per_period.items():
        observations.sort(key=lambda f: (f.get("filed") or "", f.get("accn") or ""))
        first, last = observations[0], observations[-1]
        chosen = last if RESTATEMENT_POLICY == "as_last_reported" else first
        restated = first.get("val") != last.get("val")
        sv = SourcedValue(
            value=chosen.get("val"),
            unit=unit,
            period_end=end,
            fiscal_year=_fy_label(end, fy_index),
            fiscal_period="FY",
            form=chosen.get("form"),
            accession=chosen.get("accn"),
            source_url=_filing_index_url(cik, chosen.get("accn", "")),
            xbrl_tag=tag,
            filed=chosen.get("filed"),
            restated=restated,
            originally_reported=first.get("val") if restated else None,
        )
        # Belt and braces: if two period ends still land on the same label,
        # keep the later-ending one rather than letting a year vanish.
        prior = by_year.get(sv.fiscal_year)
        if prior is None or (sv.period_end or "") > (prior.period_end or ""):
            by_year[sv.fiscal_year] = sv
    return [by_year[k] for k in sorted(by_year)]


def merged_series(facts: dict, cik: int, tags: list[str],
                  fy_index: Optional[dict[str, int]] = None
                  ) -> tuple[list[SourcedValue], list[str]]:
    """
    Merge candidate tags into ONE series, per fiscal year, honouring tag
    priority. Returns (series, tags_actually_used).

    This is the fix for the truncation bug: a filer that used `Revenues` through
    FY2018 and `RevenueFromContractWithCustomerExcludingAssessedTax` from FY2019
    now yields a complete series instead of whichever half came first.
    """
    if fy_index is None:
        fy_index = _fiscal_year_index(facts)
    by_year: dict[int, SourcedValue] = {}
    used: list[str] = []
    for tag in tags:  # highest preference first
        series = annual_series(facts, cik, tag, fy_index)
        if not series:
            continue
        contributed = False
        for sv in series:
            fy = sv.fiscal_year
            if fy is None or fy in by_year:
                continue  # a higher-priority tag already covers this year
            by_year[fy] = sv
            contributed = True
        if contributed:
            used.append(tag)
    return [by_year[k] for k in sorted(by_year)], used


def get_financial_concept(query: str, metric_or_tag: str, years: int = 6) -> dict:
    """
    Escape-hatch / flexibility tool: return the annual series for either a
    friendly metric name (see CONCEPT_MAP) or a raw US-GAAP tag.
    """
    _validate_years(years)
    comp = _resolve_cik(query)
    candidates = CONCEPT_MAP.get(metric_or_tag)
    if candidates is None:
        if not _TAG_RE.match(metric_or_tag):
            raise InvalidTag(
                f"'{metric_or_tag}' is neither a known metric name "
                f"({', '.join(sorted(CONCEPT_MAP))}) nor a valid US-GAAP tag."
            )
        candidates = [metric_or_tag]

    facts = get_company_facts(comp["cik10"])
    series, used = merged_series(facts, comp["cik"], candidates)
    if not series:
        # Success with a structured absence, not an error: EDGAR answered, and
        # the answer was "this filer does not report that". `note` stays for
        # backward compatibility; `absence` is the machine-readable form.
        return {
            "company": comp,
            "metric": metric_or_tag,
            "tags_tried": candidates,
            "series": [],
            "absence": _absence("TAG_NOT_REPORTED", candidates),
            "note": f"No annual data found for '{metric_or_tag}' "
                    f"(tried tags: {', '.join(candidates)}).",
        }
    series = series[-years:]
    return {
        "company": comp,
        "metric": metric_or_tag,
        "xbrl_tags_used": used,
        "mixed_tag_basis": len(used) > 1,
        "tags_tried": candidates,
        "series": [sv.to_dict() for sv in series],
    }


# --------------------------------------------------------------------------- #
# Structured absence
# --------------------------------------------------------------------------- #
#
# One rule, applied everywhere:
#
#   Reaching EDGAR and getting a valid answer of "nothing" is a SUCCESS with an
#   explicit, structured absence. Only failing to OBTAIN an answer is an error.
#
# Before this, the same condition produced four different shapes depending on
# which tool you asked. The worst was get_key_financials handing back a bare
# `[]` for an untagged line item with no explanation anywhere in the payload:
# screening AMD returned "total_liabilities": [] and a reader could not tell
# "this filer does not tag it" from "our fetch failed". compute_screening_metrics
# listed it under data_quality.missing_line_items, but the tool one level down
# gave you nothing.
#
# This makes gaps legible. It does not fill them — invariant 7 still holds:
# missing data is reported, never estimated.

_MAX_YEARS = 25  # EDGAR's XBRL era starts ~2009; beyond this there is nothing to fetch.


def _validate_years(years: int, *, maximum: int = _MAX_YEARS) -> int:
    """Reject a nonsense window before it produces a confidently wrong answer.

    This is not defensive padding. `years=-5` produced an empty fiscal-year
    window, which tripped the same "nothing found" branch as a genuine IFRS
    filer — so asking for Apple with a negative window returned *"No XBRL
    financial data found for Apple Inc. Foreign or non-standard filers (20-F /
    IFRS) may not report US-GAAP XBRL facts."* Apple reports XBRL exhaustively.
    The tool blamed the filer for the caller's mistake, which is precisely the
    plausible-but-wrong failure this codebase exists to avoid.
    """
    if not isinstance(years, int) or isinstance(years, bool):
        raise InvalidArgument(f"`years` must be an integer, got {type(years).__name__}.")
    if years < 1:
        raise InvalidArgument(
            f"`years` must be at least 1, got {years}. A non-positive window "
            "yields no fiscal years, which is not the same as the filer having "
            "no data."
        )
    if years > maximum:
        raise InvalidArgument(
            f"`years` must be at most {maximum}, got {years}. EDGAR's XBRL era "
            "begins around 2009, so a longer window cannot return more."
        )
    return years


def _validate_limit(limit: int, *, maximum: int = 100) -> int:
    """Same reasoning as `_validate_years`, for filing-list pagination."""
    if not isinstance(limit, int) or isinstance(limit, bool):
        raise InvalidArgument(f"`limit` must be an integer, got {type(limit).__name__}.")
    if limit < 1:
        raise InvalidArgument(f"`limit` must be at least 1, got {limit}.")
    if limit > maximum:
        raise InvalidArgument(f"`limit` must be at most {maximum}, got {limit}.")
    return limit


ABSENCE_CODES = {
    "TAG_NOT_REPORTED": "The filer has never reported any of the candidate tags.",
    "TAG_DISCONTINUED": "The filer reported this once but stopped before the "
                        "reference fiscal year, so using it would pair a stale "
                        "numerator with a current denominator.",
    "OUTSIDE_WINDOW": "Reported, but only outside the requested fiscal-year window.",
}


def _absence(code: str, tags_tried: list[str], *,
             last_reported: Optional[int] = None,
             reference_fiscal_year: Optional[int] = None) -> dict:
    """Describe *why* a series is empty, in a shape every tool shares."""
    note = ABSENCE_CODES.get(code, "")
    if code == "TAG_DISCONTINUED" and last_reported:
        note = (f"Last reported for fiscal {last_reported}; the screen is anchored "
                f"to {reference_fiscal_year}. Excluded rather than carried forward.")
    return {
        "code": code,
        "tags_tried": tags_tried,
        "last_reported_fiscal_year": last_reported,
        "note": note,
    }


def _classify_absence(metric: str, tags_tried: list[str],
                      full_series: list, reference_fy: Optional[int]) -> dict:
    """Work out which kind of nothing this is.

    `full_series` is the unwindowed series — the distinction between "never
    reported" and "reported, then abandoned" is only visible before windowing,
    and it is the distinction a reader most needs.
    """
    if not full_series:
        return _absence("TAG_NOT_REPORTED", tags_tried)
    years = [sv.fiscal_year for sv in full_series if sv.fiscal_year is not None]
    last = max(years) if years else None
    if last is not None and reference_fy is not None and last < reference_fy:
        return _absence("TAG_DISCONTINUED", tags_tried, last_reported=last,
                        reference_fiscal_year=reference_fy)
    return _absence("OUTSIDE_WINDOW", tags_tried, last_reported=last,
                    reference_fiscal_year=reference_fy)


# The line items that define "which fiscal year is this screen about".
_ANCHOR_ITEMS = ("revenue", "total_assets", "net_income", "operating_income")


def _all_line_items(query: str, years: int
                    ) -> tuple[dict, dict[str, list[SourcedValue]],
                               dict[str, list[str]], Optional[int],
                               dict[str, list[SourcedValue]]]:
    """
    Fetch every CONCEPT_MAP line item from a single companyfacts call, then
    window every series to the SAME fiscal-year range.

    Windowing by fiscal year rather than by `series[-years:]` matters more than it
    looks: filers abandon tags. Target stopped tagging `GrossProfit` after FY2017,
    so a positional slice hands back FY2013-FY2017 gross profit sitting next to
    FY2021-FY2025 revenue — and the last item of each list is then silently
    combined into a margin spanning eight years. Anchoring to a reference year
    turns that into an honest gap.
    """
    comp = _resolve_cik(query)
    facts = get_company_facts(comp["cik10"])
    fy_index = _fiscal_year_index(facts)

    full: dict[str, list[SourcedValue]] = {}
    tags_used: dict[str, list[str]] = {}
    for metric, tags in CONCEPT_MAP.items():
        series, used = merged_series(facts, comp["cik"], tags, fy_index)
        full[metric] = series
        tags_used[metric] = used

    anchor_years = [sv.fiscal_year for m in _ANCHOR_ITEMS for sv in full.get(m, [])
                    if sv.fiscal_year is not None]
    all_years = [sv.fiscal_year for s in full.values() for sv in s
                 if sv.fiscal_year is not None]
    reference_fy = max(anchor_years) if anchor_years else (
        max(all_years) if all_years else None)

    if reference_fy is None:
        return comp, full, tags_used, None, full
    floor = reference_fy - years + 1
    windowed = {
        metric: [sv for sv in series
                 if sv.fiscal_year is not None and floor <= sv.fiscal_year <= reference_fy]
        for metric, series in full.items()
    }
    return comp, windowed, tags_used, reference_fy, full


def get_key_financials(query: str, years: int = 5) -> dict:
    """
    Curated multi-year financials across income statement, balance sheet and
    cash flow. Every value is a SourcedValue (period + form + accession + URL).
    """
    _validate_years(years)
    comp, series_map, tags_used, reference_fy, full = _all_line_items(query, years)
    if not any(series_map.values()):
        raise NoXBRLData(
            f"No XBRL financial data found for {comp['name']} "
            f"(CIK {comp['cik']}). Foreign or non-standard filers (20-F / IFRS) "
            "may not report US-GAAP XBRL facts."
        )
    mixed = sorted(m for m, used in tags_used.items() if len(used) > 1)

    # Every empty line item gets a reason. Without this the caller sees a bare
    # `[]` and cannot distinguish an untagged concept from a failed fetch — which
    # is exactly what screening AMD produced for total_liabilities.
    absent = {
        metric: _classify_absence(metric, CONCEPT_MAP.get(metric, []),
                                  full.get(metric, []), reference_fy)
        for metric, series in series_map.items() if not series
    }

    result = {
        "company": comp,
        "years_requested": years,
        "reference_fiscal_year": reference_fy,
        "restatement_policy": RESTATEMENT_POLICY,
        "xbrl_tags_used": {m: u for m, u in tags_used.items() if u},
        "mixed_tag_basis": mixed,
        "line_items": {
            metric: [sv.to_dict() for sv in series]
            for metric, series in series_map.items()
        },
    }
    if absent:
        result["absent_line_items"] = absent
        result["absence_note"] = (
            f"{len(absent)} of {len(series_map)} line items are empty. Each is "
            "explained in `absent_line_items` with the tags tried and why nothing "
            "was usable. These are gaps in the filer's XBRL, not fetch failures — "
            "report them as gaps and do not estimate around them."
        )
    return result


# --------------------------------------------------------------------------- #
# Screening metrics — computed in Python, with meaningfulness decided in code
# --------------------------------------------------------------------------- #

def _latest(series: list[SourcedValue]) -> Optional[SourcedValue]:
    return series[-1] if series else None


def _at(series: list[SourcedValue], fy: Optional[int]) -> Optional[SourcedValue]:
    """The value for one exact fiscal year — never a stale neighbour."""
    if fy is None:
        return None
    for sv in series:
        if sv.fiscal_year == fy:
            return sv
    return None


def _guarded_ratio(numer: Optional[float], denom: Optional[float]
                   ) -> tuple[Optional[float], bool, Optional[str]]:
    """
    Divide, and say whether the answer means anything.

    A ratio can be arithmetically perfect and analytically worthless — debt/equity
    on a company with a $2m stockholders' deficit produces -417x, which reads as
    a number but is really the sentence "equity is negative". Deciding that in
    code (not in a prompt) is what makes the output trustworthy.
    """
    if numer is None or denom is None:
        return None, False, "input not reported"
    if denom == 0:
        return None, False, "denominator is zero"
    value = numer / denom
    if denom < 0:
        return value, False, (
            "denominator is negative — the ratio is not interpretable; "
            "report the negative balance itself instead"
        )
    if abs(denom) < abs(numer) * THRESHOLDS["near_zero_denominator_ratio"]:
        return value, False, (
            "denominator is near zero relative to the numerator — "
            "the ratio is unstable and should not be quoted"
        )
    return value, True, None


def _metric(value, unit, inputs, meaningful=True, caveat=None, **extra) -> dict:
    out = {
        "value": value,
        "unit": unit,
        "meaningful": meaningful,
        "caveat": caveat,
        "inputs": [x.to_dict() for x in inputs if x],
    }
    out.update(extra)
    return out


def _today():
    """Indirection so tests can freeze 'now' — staleness is time-dependent, and a
    test that starts failing next winter is worse than no test."""
    from datetime import date
    return date.today()


def _months_since(period_end: Optional[str]) -> Optional[float]:
    if not period_end:
        return None
    try:
        from datetime import date
        end = date.fromisoformat(period_end)
    except (TypeError, ValueError):
        return None
    return (_today() - end).days / 30.44


