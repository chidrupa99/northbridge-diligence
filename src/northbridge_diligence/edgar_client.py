def _detect_flags(metrics: dict, vals: dict, svs: dict,
                  latest_period_end: Optional[str],
                  mixed: list[str], restated: list[str],
                  stale_items: Optional[dict[str, int]] = None) -> list[dict]:
    """
    Red flags, decided here. Each is {code, severity, message, evidence}.

    The model's job is to narrate these; it is not asked to spot them. That
    boundary is the whole trust argument: an analyst can re-run this function
    and get the same flags every time, which is not true of a prompt.
    """
    flags: list[dict] = []

    def add(code, severity, message, evidence=()):
        # Severity comes from FLAG_CATALOGUE, not from the call site, so the
        # catalogue exposed as an MCP resource cannot drift from the behaviour --
        # there is exactly one place a severity is written down. An unknown code
        # raises KeyError, which is correct: it is a programming error.
        flags.append({
            "code": code,
            "severity": FLAG_CATALOGUE[code]["severity"],
            "message": message,
            "evidence": [sv.to_dict() for sv in evidence if sv],
        })

    eq, oi, ni = vals.get("stockholders_equity"), vals.get("operating_income"), vals.get("net_income")
    ocf, ebitda = vals.get("operating_cash_flow"), vals.get("ebitda")

    if eq is not None and eq < 0:
        add("NEGATIVE_EQUITY", "high",
            f"Stockholders' equity is negative ({eq:,.0f}). Leverage ratios that "
            "divide by equity are not meaningful; treat this as a capital-structure "
            "issue in its own right.",
            [svs.get("stockholders_equity")])

    if ni is not None and oi is not None and ni > 0 and oi < 0:
        add("EARNINGS_QUALITY", "high",
            f"Net income is positive ({ni:,.0f}) while operating income is negative "
            f"({oi:,.0f}) — roughly {ni - oi:,.0f} of profit comes from outside the "
            "operating business. Identify the non-operating item before treating "
            "this company as profitable.",
            [svs.get("net_income"), svs.get("operating_income")])

    cr = metrics.get("current_ratio")
    if cr and cr.get("meaningful") and cr["value"] is not None \
            and cr["value"] < THRESHOLDS["current_ratio_low"]:
        add("LIQUIDITY", "high",
            f"Current ratio is {cr['value']:.2f} (below "
            f"{THRESHOLDS['current_ratio_low']:.1f}) — current liabilities exceed "
            "current assets.", [svs.get("current_assets"), svs.get("current_liabilities")])

    de = metrics.get("debt_to_ebitda")
    if de and de.get("meaningful") and de["value"] is not None \
            and de["value"] > THRESHOLDS["debt_to_ebitda_high"]:
        add("LEVERAGE", "high",
            f"Debt/EBITDA is {de['value']:.1f}x, above the "
            f"{THRESHOLDS['debt_to_ebitda_high']:.0f}x screening threshold.",
            [svs.get("long_term_debt"), svs.get("current_debt")])

    ic = metrics.get("interest_coverage")
    if ic and ic.get("meaningful") and ic["value"] is not None \
            and ic["value"] < THRESHOLDS["interest_coverage_low"]:
        add("COVERAGE", "high",
            f"Interest coverage is {ic['value']:.1f}x, below "
            f"{THRESHOLDS['interest_coverage_low']:.0f}x.",
            [svs.get("operating_income"), svs.get("interest_expense")])

    if ebitda is not None and ebitda < 0:
        add("NEGATIVE_EBITDA", "high",
            f"EBITDA is negative ({ebitda:,.0f}); leverage multiples built on it "
            "are not meaningful.",
            [svs.get("operating_income"), svs.get("depreciation_amortization")])

    yoy = metrics.get("revenue_yoy")
    if yoy and yoy["value"] is not None and yoy["value"] < THRESHOLDS["revenue_decline_pct"]:
        add("REVENUE_DECLINE", "medium",
            f"Revenue fell {abs(yoy['value']) * 100:.1f}% year over year.",
            [svs.get("revenue")])

    if ocf is not None and ocf < 0:
        add("CASH_BURN", "medium",
            f"Operating cash flow is negative ({ocf:,.0f}) in the latest fiscal year.",
            [svs.get("operating_cash_flow")])

    months = _months_since(latest_period_end)
    if months is not None and months > THRESHOLDS["stale_data_months"]:
        add("STALE_DATA", "medium",
            f"The most recent annual figures are ~{months:.0f} months old "
            f"(period ended {latest_period_end}). Check for a more recent 10-Q "
            "before relying on this screen.")

    missing = [m for m in ("revenue", "operating_income", "total_assets",
                           "stockholders_equity") if vals.get(m) is None]
    if missing:
        add("MISSING_DATA", "info",
            "Not reported in XBRL for the reference fiscal year: " +
            ", ".join(missing) + ". These are absent, not zero.")

    if stale_items:
        add("TAG_DISCONTINUED", "info",
            "The filer stopped tagging these before the reference year, so they "
            "are excluded rather than carried forward: " +
            ", ".join(f"{m} (last seen FY{fy})" for m, fy in sorted(stale_items.items()))
            + ".")

    if mixed:
        add("MIXED_TAG_BASIS", "info",
            "Series stitched across more than one US-GAAP tag (the filer changed "
            "tagging mid-history): " + ", ".join(mixed) +
            ". Comparability across years is usually fine but worth a spot-check.")

    if restated:
        add("RESTATED", "info",
            "A later filing reported a different value for a prior period: " +
            ", ".join(restated) + f". Policy in force: {RESTATEMENT_POLICY}.")

    return flags


def compute_screening_metrics(query: str, years: int = 5) -> dict:
    """
    The full screen result: growth, margins, leverage, liquidity — arithmetic done
    here in code — plus code-detected red flags and a data-quality summary. Each
    metric carries the sourced inputs it was computed from and a `meaningful`
    boolean, so the caller never has to decide whether a ratio is quotable.
    """
    _validate_years(years)
    comp, s, tags_used, reference_fy, full = _all_line_items(query, years)
    if not any(s.values()) or reference_fy is None:
        raise NoXBRLData(
            f"No XBRL financial data found for {comp['name']} (CIK {comp['cik']})."
        )

    # Everything below is pinned to ONE fiscal year. A line item the filer
    # stopped tagging is absent, not backfilled from an older year.
    svs: dict[str, Optional[SourcedValue]] = {m: _at(v, reference_fy) for m, v in s.items()}
    vals: dict[str, Optional[float]] = {
        m: (sv.value if sv else None) for m, sv in svs.items()
    }
    # Line items the filer once tagged and later abandoned. Reported as a gap,
    # never carried forward into the reference year.
    stale_items = {
        m: _latest(v).fiscal_year
        for m, v in full.items()
        if svs.get(m) is None and v and _latest(v).fiscal_year is not None
    }

    # Guard against mixing currencies in a single ratio.
    units = {sv.unit for sv in svs.values() if sv and sv.value is not None}
    monetary_units = {u for u in units if u != "pure"}
    single_currency = len(monetary_units) <= 1
    currency = next(iter(monetary_units), "USD")

    metrics: dict[str, dict] = {}
    rev_series = s.get("revenue", [])

    # --- Growth -----------------------------------------------------------
    last = _at(rev_series, reference_fy)
    if last is not None and len(rev_series) >= 2:
        first = rev_series[0]
        n = (last.fiscal_year or 0) - (first.fiscal_year or 0)
        cagr = None
        if first.value and last.value and first.value > 0 and last.value > 0 and n > 0:
            cagr = (last.value / first.value) ** (1 / n) - 1
        metrics["revenue_cagr"] = _metric(
            cagr, "ratio", [first, last], meaningful=cagr is not None,
            caveat=None if cagr is not None else "needs positive revenue in both years",
            window=f"FY{first.fiscal_year}-FY{last.fiscal_year}")
        prior = _at(rev_series, reference_fy - 1)
        if prior is not None:
            yoy, ok, caveat = _guarded_ratio(
                (last.value - prior.value)
                if (last.value is not None and prior.value is not None) else None,
                prior.value)
            metrics["revenue_yoy"] = _metric(yoy, "ratio", [prior, last], ok, caveat)

    # --- Margins (latest FY) ---------------------------------------------
    rev = vals.get("revenue")
    gp, gp_sv = vals.get("gross_profit"), svs.get("gross_profit")
    if gp is None and rev is not None and vals.get("cost_of_revenue") is not None:
        gp = rev - vals["cost_of_revenue"]           # derive when not tagged
        gp_sv = svs.get("cost_of_revenue")
    oi, ni = vals.get("operating_income"), vals.get("net_income")

    for name, numer, numer_sv in (
        ("gross_margin", gp, gp_sv),
        ("operating_margin", oi, svs.get("operating_income")),
        ("net_margin", ni, svs.get("net_income")),
    ):
        if numer is None or rev is None:
            continue
        value, ok, caveat = _guarded_ratio(numer, rev)
        metrics[name] = _metric(value, "ratio", [numer_sv, svs.get("revenue")], ok, caveat)

    # --- Leverage ---------------------------------------------------------
    ltd, cd = vals.get("long_term_debt"), vals.get("current_debt")
    debt_inputs = [svs.get("long_term_debt"), svs.get("current_debt")]
    total_debt = None
    if ltd is not None or cd is not None:
        total_debt = (ltd or 0) + (cd or 0)
        metrics["total_debt"] = _metric(
            total_debt, currency, debt_inputs,
            caveat=("approximated as long-term + current debt tags; finance leases "
                    "and other debt-like items are not fully assembled"))

    da = vals.get("depreciation_amortization")
    ebitda = (oi + da) if (oi is not None and da is not None) else None
    if ebitda is not None:
        metrics["ebitda"] = _metric(
            ebitda, currency,
            [svs.get("operating_income"), svs.get("depreciation_amortization")],
            caveat="EBITDA proxied as operating income + D&A")
    vals["ebitda"] = ebitda

    if total_debt is not None:
        value, ok, caveat = _guarded_ratio(total_debt, vals.get("stockholders_equity"))
        metrics["debt_to_equity"] = _metric(
            value, "x", debt_inputs + [svs.get("stockholders_equity")], ok, caveat)
        if ebitda is not None:
            value, ok, caveat = _guarded_ratio(total_debt, ebitda)
            if ebitda < 0:
                ok, caveat = False, "EBITDA is negative — the multiple is not meaningful"
            metrics["debt_to_ebitda"] = _metric(
                value, "x", debt_inputs + [svs.get("operating_income")], ok, caveat)

    # --- Liquidity / coverage --------------------------------------------
    value, ok, caveat = _guarded_ratio(vals.get("current_assets"), vals.get("current_liabilities"))
    if value is not None:
        metrics["current_ratio"] = _metric(
            value, "x", [svs.get("current_assets"), svs.get("current_liabilities")], ok, caveat)

    value, ok, caveat = _guarded_ratio(oi, vals.get("interest_expense"))
    if value is not None:
        metrics["interest_coverage"] = _metric(
            value, "x", [svs.get("operating_income"), svs.get("interest_expense")], ok, caveat)
        if oi is not None and oi < 0:
            metrics["interest_coverage"]["meaningful"] = False
            metrics["interest_coverage"]["caveat"] = (
                "operating income is negative — there are no operating earnings to "
                "cover interest")

    if vals.get("operating_cash_flow") is not None:
        metrics["operating_cash_flow_latest"] = _metric(
            vals["operating_cash_flow"], currency, [svs.get("operating_cash_flow")])

    if not single_currency:
        for m in metrics.values():
            m["meaningful"] = False
            m["caveat"] = (m.get("caveat") or "") + \
                " | line items are reported in more than one currency; ratios are unsafe"

    mixed = sorted(m for m, used in tags_used.items() if len(used) > 1)
    restated = sorted(m for m, sv in svs.items() if sv and sv.restated)
    anchor = svs.get("revenue") or svs.get("total_assets")
    latest_period_end = anchor.period_end if anchor else None

    flags = _detect_flags(metrics, vals, svs, latest_period_end, mixed, restated,
                          stale_items)

    return {
        "company": comp,
        "as_of_fiscal_year": reference_fy,
        "as_of_period_end": latest_period_end,
        "currency": currency,
        "metrics": metrics,
        "flags": flags,
        "data_quality": {
            "mixed_tag_basis": mixed,
            "restated_line_items": restated,
            "missing_line_items": sorted(m for m, v in vals.items()
                                         if v is None and m != "ebitda"),
            "last_reported_before_reference_year": stale_items,
            "restatement_policy": RESTATEMENT_POLICY,
            "single_currency": single_currency,
        },
        "thresholds": THRESHOLDS,
        "note": "All ratios computed in code from the sourced inputs listed on each "
                "metric. A metric with meaningful=false must NOT be quoted as a "
                "figure — state its caveat instead. Missing metrics mean the "
                "underlying tag was not reported, not that the value is zero.",
    }


