def get_company_profile(query: str) -> dict:
    comp = _resolve_cik(query)
    subs = _get_submissions(comp["cik10"])
    recent = subs.get("filings", {}).get("recent", {})

    latest = {}
    for want in ("10-K", "10-Q"):
        for i, form in enumerate(recent.get("form", [])):
            if form == want:
                latest[want] = {
                    "filed": recent["filingDate"][i],
                    "period": recent["reportDate"][i],
                    "accession": recent["accessionNumber"][i],
                    "url": _document_url(
                        comp["cik"], recent["accessionNumber"][i],
                        recent["primaryDocument"][i],
                    ),
                }
                break

    return {
        "cik": comp["cik"],
        "name": subs.get("name", comp["name"]),
        "tickers": subs.get("tickers", []),
        "exchanges": subs.get("exchanges", []),
        "sic": subs.get("sic"),
        "industry": subs.get("sicDescription"),
        "fiscal_year_end": subs.get("fiscalYearEnd"),
        "state": subs.get("stateOfIncorporation"),
        "latest_filings": latest,
        "source_url": (
            "https://www.sec.gov/cgi-bin/browse-edgar?action=getcompany"
            f"&CIK={comp['cik10']}&type=10-K"
        ),
    }


