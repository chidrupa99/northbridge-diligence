"""
edgar_client.py — a thin, defensive wrapper around the SEC EDGAR REST APIs.

Design notes for whoever picks this up cold:
  * This module holds ALL the EDGAR logic. server.py is a thin MCP shim on top,
    so the same functions can be unit-tested and reused off-server (the sample
    memo is generated by calling these directly, and the test suite drives them
    against recorded fixtures with no network).
  * Every financial datapoint carries its provenance: the accession number of
    the filing it came from and a resolvable EDGAR URL. Attribution is
    structural, not decorative — see `SourcedValue`.
  * EDGAR is an "imperfect vendor system": tags vary by company, values are
    restated, sections are messy HTML. We fail soft and say so rather than
    guessing.
  * JUDGMENT LIVES IN CODE. Ratio meaningfulness (negative/near-zero
    denominators) and red-flag detection are computed here and returned as
    structured objects. The model narrates them; it does not decide them.

Fetch strategy:
  * One `companyfacts` call per company gives us EVERY XBRL fact the filer has
    ever reported. We fetch it once, cache it, and slice locally. The earlier
    design issued one `companyconcept` call per line item (~17 per screen, and
    twice over when metrics and financials were both requested).

SEC fair-access rules (learned the hard way — a missing header returns HTTP 403):
  * A descriptive User-Agent with contact info is REQUIRED. Set EDGAR_USER_AGENT.
  * Stay under ~10 requests/second. We self-throttle and back off on 429/5xx.
"""

