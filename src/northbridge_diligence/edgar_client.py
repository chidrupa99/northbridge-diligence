def _accn_nodash(accn: str) -> str:
    return accn.replace("-", "")


def _filing_index_url(cik: int, accn: str) -> Optional[str]:
    """A resolvable link to the filing's index page (works for any accession)."""
    if not accn:
        return None
    return (
        f"https://www.sec.gov/Archives/edgar/data/{cik}/{_accn_nodash(accn)}/"
        f"{accn}-index.htm"
    )


def _document_url(cik: int, accn: str, primary_doc: str) -> str:
    return (
        f"https://www.sec.gov/Archives/edgar/data/{cik}/"
        f"{_accn_nodash(accn)}/{primary_doc}"
    )


@dataclass
class SourcedValue:
    """A single number that knows where it came from."""
    value: Optional[float]
    unit: str                     # e.g. "USD"
    period_end: Optional[str]     # e.g. "2024-09-28"
    fiscal_year: Optional[int]
    fiscal_period: Optional[str]  # "FY", "Q1", ...
    form: Optional[str]           # "10-K", "10-K/A"
    accession: Optional[str]
    source_url: Optional[str]
    xbrl_tag: Optional[str] = None
    filed: Optional[str] = None
    # Restatement transparency: set when an earlier filing reported a different
    # number for the same period.
    restated: bool = False
    originally_reported: Optional[float] = None

    def to_dict(self) -> dict:
        return asdict(self)


